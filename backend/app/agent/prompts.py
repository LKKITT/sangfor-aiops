def device_context_message(device: dict, status: dict | None) -> str:
    """每轮对话注入的设备运行时上下文。"""
    if device.get("type") == "global" or str(device.get("id", "")) == "global":
        # 全局模式（不绑定单一设备）
        lines = [f"当前为**全局模式**：不绑定单一设备，可操作全部已添加设备——"
                 f"深信服设备 {device.get('sangfor_count', 0)} 台、"
                 f"网络设备 {device.get('netdev_count', 0)} 台（仅华为/H3C/锐捷可对话操作）。"]
        lines.append("深信服设备类工具调用时必须用 devices 参数指定目标设备"
                     "（传 [\"all\"] 表示全部深信服设备；仅一台深信服设备时会自动定向）；"
                     "网络设备用 netdev_* 工具的 devices 参数同理（[\"all\"]=全部网络设备）。"
                     "用户未指明设备时先询问再操作。")
        return "\n".join(lines)
    dev_id = str(device.get("id", ""))
    if dev_id.startswith("nd_"):
        # 网络设备（SSH 交换机/路由器）：无 mode/readonly 概念，按厂家给能力提示
        vendor = device.get("vendor", "")
        vendor_cn = {"huawei": "华为 VRP", "h3c": "H3C Comware", "ruijie": "锐捷 RGSOS"}.get(
            vendor, vendor)
        lines = [f"当前目标设备：{device.get('name')}（网络设备 · {vendor_cn}，"
                 f"管理地址：{device.get('host', '')}，型号：{device.get('model') or '未知'}）"]
        if device.get("group_name"):
            lines.append(f"所属分组：{device['group_name']}")
        lines.append("设备类型提示：该设备为网络设备（SSH 接入），请使用 netdev_* 工具查询与配置；"
                     "深信服专用工具（NAT/ACL/备份等）不适用于该设备。")
        return "\n".join(lines)
    lines = [f"当前目标设备：{device.get('name')}（类型：{device.get('type')}，模式：{device.get('mode')}）"]
    if status:
        lines.append(
            f"设备概况：软件版本 {status.get('sw_version', '未知')}，型号 {status.get('model', '未知')}，"
            f"CPU {status.get('cpu_usage', 0)}%，内存 {status.get('memory_usage', 0)}%，"
            f"磁盘 {status.get('disk_usage', 0)}%，"
            f"会话数 {status.get('session_count', 0)}")
    if device.get("readonly"):
        lines.append("注意：该设备处于只读模式，变更类操作会被拒绝（网络设备不受此限制，可用 netdev_* 工具操作）。")
    # 设备类型能力提示
    dtype = device.get("type", "af")
    if dtype == "ac":
        lines.append("设备类型提示：该设备为 AC（上网行为管理），支持用户绑定、ACL 策略、自定义应用等；不支持 NAT 配置。")
    elif dtype == "af":
        lines.append("设备类型提示：该设备为 AF（下一代防火墙），支持 NAT、ACL、路由、用户绑定、网络对象、黑白名单等全功能。")
    elif dtype == "scp":
        lines.append("设备类型提示：该设备为 SCP（云计算平台，纳管 HCI 节点），只读接入："
                     "可查询集群（计算/存储资源）、版本、物理机及其网口功能 IP、虚拟机及其网卡端口组、存储；"
                     "不支持任何配置变更（NAT/ACL/绑定等防火墙概念不适用）。")
    lines.append("全局提示：也可通过工具的 devices 参数跨设备操作其他深信服设备，"
                 "或用 netdev_* 工具操作网络设备（华为/H3C/锐捷），无需切换会话绑定。")
    return "\n".join(lines)


def memory_injection_message(memory_items: list[dict]) -> str | None:
    """构建长期记忆注入消息。"""
    if not memory_items:
        return None
    parts = ["## 历史记忆（来自之前的对话）"]
    for item in memory_items:
        cat = {"fact": "事实", "preference": "用户偏好", "action_history": "操作记录",
               "device_context": "设备上下文"}.get(item.get("category", "fact"), "信息")
        parts.append(f"- [{cat}] {item['content']}")
    return "\n".join(parts)


def memory_extract_prompt() -> str:
    """对话结束后一次性提取「会话摘要 + 长期记忆事实」的合并 prompt（省一次后台 LLM 调用）。"""
    return """请基于这段对话完成两项提取任务，严格按以下固定格式输出，不要输出任何其他内容：
[摘要]
<用 2-3 句话概括本次对话：用户询问/操作的主要事项、设备相关的重要信息（配置变更、风险发现等）>
[事实]
<提取值得长期记住的重要事实，每条一行，格式：[类型] 内容；没有则此节留空>

事实提取范围（仅当对话中确实存在时输出）：
1. 用户偏好或习惯（如：用户喜欢先检查再操作、用户关注安全策略等）
2. 设备的重要配置决策或发现
3. 用户明确表达的观点或要求"""
